#!/usr/bin/env bash
#
# common.sh — Shared utilities for all deploy scripts.
#
# Source this file to get colour helpers, SSH utilities, logging, and path defaults.
# All pipeline scripts (build_venv, sync_code, etc.) expect this to be sourced first.
#
# Usage:
#   source deploy/common.sh
#

# ── Colour helpers ──────────────────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m'

# ── Logging helpers ─────────────────────────────────────────────────────────
log_info()    { echo -e "${BLUE}$*${NC}"; }
log_success() { echo -e "${GREEN}$*${NC}"; }
log_warn()    { echo -e "${YELLOW}$*${NC}"; }
log_error()   { echo -e "${RED}Error:${NC} $*"; }
log_step()    { echo -e "${YELLOW}⚙ $*${NC}"; }
log_done()    { echo -e "${GREEN}✔ $*${NC}"; }

# ── Path defaults ───────────────────────────────────────────────────────────
# These can be overridden before sourcing.
DEPLOY_DIR="${DEPLOY_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}"
REPO_ROOT="${REPO_ROOT:-$(cd "$DEPLOY_DIR/.." && pwd)}"
REPO_NAME="${REPO_NAME:-$(basename "$REPO_ROOT")}"
DOCKER_IMAGE="${DOCKER_IMAGE:-elemental}"
DEPLOY_LOGS_DIR="${DEPLOY_LOGS_DIR:-${DEPLOY_DIR}/logs}"

# ── Remote path setup ──────────────────────────────────────────────────────
# Call setup_remote_paths after REMOTE_PROJECT_DIR and REPO_NAME are set.
# REMOTE_PROJECT_DIR is the workspace root (e.g. /workspace).
# Code lives at REMOTE_CODE_DIR = /workspace/<repo_name>
# Logs live at  REMOTE_LOGS_DIR = /workspace/logs/<repo_name>
setup_remote_paths() {
    REMOTE_CODE_DIR="${REMOTE_PROJECT_DIR}/${REPO_NAME}"
    REMOTE_LOGS_DIR="${REMOTE_PROJECT_DIR}/logs/${REPO_NAME}"
    REMOTE_VENV_DIR="${REMOTE_CODE_DIR}/.venv"
}

# ── SSH utilities ───────────────────────────────────────────────────────────
# Call build_ssh_opts after setting REMOTE_USER, REMOTE_IP, REMOTE_PORT, SSH_IDENTITY.
build_ssh_opts() {
    REMOTE_USER="${REMOTE_USER:-root}"
    REMOTE_HOST="${REMOTE_USER}@${REMOTE_IP}"

    SSH_OPTS=()
    [[ -n "${REMOTE_PORT:-}" ]] && SSH_OPTS+=(-p "$REMOTE_PORT")
    [[ -n "${SSH_IDENTITY:-}" ]] && SSH_OPTS+=(-i "$SSH_IDENTITY")

    RSYNC_SSH="ssh"
    [[ -n "${REMOTE_PORT:-}" ]] && RSYNC_SSH="$RSYNC_SSH -p $REMOTE_PORT"
    [[ -n "${SSH_IDENTITY:-}" ]] && RSYNC_SSH="$RSYNC_SSH -i $SSH_IDENTITY"

    SSH_DISPLAY=""
    [[ -n "${REMOTE_PORT:-}" ]] && SSH_DISPLAY="$SSH_DISPLAY -p $REMOTE_PORT"
    [[ -n "${SSH_IDENTITY:-}" ]] && SSH_DISPLAY="$SSH_DISPLAY -i $SSH_IDENTITY"

    return 0  # Guard: last [[ ]] && ... returns 1 when false, which trips set -e
}

# Run a command on the remote via SSH.
ssh_cmd() {
    ssh "${SSH_OPTS[@]}" "$REMOTE_HOST" "$@"
}

# Check if remote is reachable via SSH (returns 0 if reachable).
ssh_check() {
    ssh "${SSH_OPTS[@]}" -o ConnectTimeout=10 -o BatchMode=yes \
        -o StrictHostKeyChecking=no "$REMOTE_HOST" "echo ok" &>/dev/null
}

# ── Session state ───────────────────────────────────────────────────────────
# Save session state for pulse auto-restart.
# The state file is a sourceable bash file with all variables needed to
# reconstruct the full pipeline.
SESSION_STATE_FILE="${DEPLOY_LOGS_DIR}/.session_state"

save_session_state() {
    mkdir -p "$DEPLOY_LOGS_DIR"
    cat > "$SESSION_STATE_FILE" <<STATE_EOF
# Session state — auto-generated by run.sh ($(date -Iseconds))
SESSION_PROVIDER="${PROVIDER:-}"
SESSION_POD_ID="${POD_ID:-}"
SESSION_IP="${REMOTE_IP:-}"
SESSION_PORT="${REMOTE_PORT:-}"
SESSION_SSH_IDENTITY="${SSH_IDENTITY:-}"
SESSION_USER="${REMOTE_USER:-root}"
SESSION_REMOTE_PROJECT_DIR="${REMOTE_PROJECT_DIR:-/workspace}"
SESSION_REMOTE_HOME="${REMOTE_HOME:-/root}"
SESSION_POD_CONFIG="${POD_CONFIG:-}"
SESSION_PYTHON_ARGS="$(printf '%q ' "${PYTHON_ARGS[@]}")"
SESSION_NAME="${SESSION_NAME:-}"
SESSION_RUNPOD_API_KEY="${RUNPOD_API_KEY:-}"
SESSION_WANDB_API_KEY="${WANDB_API_KEY:-}"
SESSION_RECOVERY_POLICY="${RECOVERY_POLICY:-restart}"
STATE_EOF
}
